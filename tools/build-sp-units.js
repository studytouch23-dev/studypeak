function ruleHit(cond, row){
  if(cond === '*' || cond === 'else') return true;
  if(cond instanceof RegExp) return cond.test(row.type);
  return !!cond(row);
}

/* ── 3. 조립 ── */
function build(rows){
  const UNITS = {};                       // '과목|대단원|중단원' → { 소단원: { 유형: [] } }
  const CURR = {};                        // 새로 생기는 과목·중단원 (초등 수학 등)
  const miss = [], unused = new Set(Object.keys(ROUTES));
  const put = (pathStr, sub, type)=>{
    const [S, C, X] = pathStr.split('>');                  // 담는 중단원은 교육과정에도 (없으면 랩이 더함 — 이미 있으면 그대로)
    const ch = ((CURR[S] = CURR[S] || {})[C] = CURR[S][C] || []); if(!ch.includes(X)) ch.push(X);
    const k = pathStr.split('>').join('|');
    const n = UNITS[k] = UNITS[k] || {};
    (n[sub] = n[sub] || {})[type] = [];
  };
  for(const r of rows){
    if(r.lv === '초등'){
      const grades = [...new Set(r.tag.split('/').map(t=>t.split('.')[0]).filter(Boolean))];
      for(const g of grades) put(p('초등 수학', r.cat, r.sub), g+'학년', r.type);
      continue;
    }
    const key = (r.lv === '중등' ? '중등' : r.tag) + '|' + r.sub;
    const groups = ROUTES[key];
    if(!groups){ miss.push(key+' :: '+r.type); continue; }
    unused.delete(key);
    let placed = 0;
    for(const g of groups){
      const hit = g.find(([cond])=>ruleHit(cond, r));
      if(hit){ hit.slice(1).forEach(pp=>put(pp, r.sub, r.type)); placed++; }
    }
    if(!placed) miss.push(key+' :: '+r.type);
  }
  for(const k of Object.keys(UNITS)) if(k.startsWith('초등 수학|')){   // 학년 순서대로
    const n = UNITS[k]; UNITS[k] = Object.fromEntries(Object.keys(n).sort((a, b)=>parseInt(a) - parseInt(b)).map(g=>[g, n[g]]));
  }
  return { UNITS, CURR, miss, unused:[...unused] };
}

function lookup(rows){                     // (학교급, 소분류, 유형) → [대분류, 태그들]
  const L = {};
  for(const r of rows){
    const k = r.lv+'|'+r.sub+'|'+r.type;
    if(!L[k]) L[k] = [r.cat, r.tag];
    else if(L[k][0] !== r.cat) throw new Error('대분류가 둘인 유형: '+k);
    else if(!L[k][1].split('/').includes(r.tag)) L[k][1] += '/'+r.tag;
  }
  return L;
}

