/* ── 1. md 파싱 ── */
function parseMaster(text){
  const rows = []; let lv = '', cat = '', sub = '';
  for(const line of text.split('\n')){
    let m;
    if((m = line.match(/^# (초등|중등|고등)\s*$/))){ lv = m[1]; cat = sub = ''; continue; }
    if((m = line.match(/^## (.+?)(?:\s+—.*)?$/))){ cat = m[1].trim(); sub = ''; continue; }
    if((m = line.match(/^### (.+?)\s+\(\d+\)\s*$/))){ sub = m[1].trim(); continue; }
    if(!lv || !sub || !line.startsWith('| ') || /^\|\s*(학년|과목|-)/.test(line)) continue;
    const cells = line.slice(1, line.lastIndexOf('|')).split('|').map(s=>s.trim());
    if(cells.length < 2) continue;
    rows.push({ lv, cat, sub, tag: cells[0], type: cells.slice(1).join('|') });
  }
  return rows;
}

